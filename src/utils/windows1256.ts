const UNICODE_TO_BYTE = new Map<number, number>(UPPER_HALF.map(([byte, unicode]) => [unicode, byte]));

/** يحوّل نصاً إلى Uint8Array بترميز Windows-1256، مستبدلاً أي حرف غير مدعوم بـ "?". */
export function encodeWindows1256(text: string): Uint8Array {
  const bytes = new Uint8Array(text.length);
  for (let i = 0; i < text.length; i++) {
    const code = text.charCodeAt(i);
    if (code < 0x80) {
      bytes[i] = code;
    } else {
      bytes[i] = UNICODE_TO_BYTE.get(code) ?? 0x3f;
    }
  }
  return bytes;
}
