import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createClient} from '@supabase/supabase-js';
const read=name=>JSON.parse(fs.readFileSync(name,'utf8').replace(/^\uFEFF/,''));
const schema=name=>JSON.parse(fs.readFileSync(name,'utf8').split(/\r?\n/).find(line=>line.startsWith('{')));
const normalize=v=>typeof v==='string'?v.replaceAll('\r\n','\n'):Array.isArray(v)?v.map(normalize).sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b))):v&&typeof v==='object'?Object.fromEntries(Object.entries(v).sort(([a],[b])=>a.localeCompare(b)).map(([k,value])=>[k,normalize(value)])):v;
const original=schema('.verification/local-stack/upgraded-schema.raw');
const restored=schema('.verification/local-stack/restored-schema.raw');
// A restore into another database changes its catalog name, not the object grants.
for(const snapshot of [original,restored]) for(const grant of snapshot.grants) delete grant.table_catalog;
for(const key of Object.keys(original)) assert.equal(JSON.stringify(normalize(restored[key])),JSON.stringify(normalize(original[key])),`Restored ${key} differs`);
const data=read('verification-results/synthetic-restore.json');
assert.deepEqual(data,{tables:43,users:5,companies:2,submissions:1,payments:3,rpc:true});
const connection=read('.verification/local-stack/connection.json');
const url=connection.API_URL;
assert.equal(new URL(url).hostname,'127.0.0.1','Storage tests must target loopback');
const client=createClient(url,connection.SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const check=result=>{if(result.error)throw result.error;return result.data;};
const suffix=Date.now().toString();
const source='synthetic-backup-'+suffix,target='synthetic-restore-'+suffix;
check(await client.storage.createBucket(source,{public:false}));
check(await client.storage.createBucket(target,{public:false}));
const payload=Buffer.from('Synthetic BARAQ storage restore verification. No user data.');
check(await client.storage.from(source).upload('sample.txt',payload,{contentType:'text/plain'}));
const downloaded=check(await client.storage.from(source).download('sample.txt'));
const backup=Buffer.from(await downloaded.arrayBuffer());
fs.writeFileSync('.verification/local-stack/synthetic-storage-backup.txt',backup);
check(await client.storage.from(target).upload('sample.txt',backup,{contentType:'text/plain'}));
const recovered=Buffer.from(await check(await client.storage.from(target).download('sample.txt')).arrayBuffer());
assert.deepEqual(recovered,payload);
const report={passed:true,schemaGroups:Object.keys(original),syntheticData:data,storage:{passed:true,sourceBucket:source,restoredBucket:target,sha256:createHash('sha256').update(recovered).digest('hex')},productionBackupVerified:false,productionFilesRestored:false};
fs.writeFileSync('verification-results/local-restore-verification.json',JSON.stringify(report,null,2));
console.log('PASS restored schema, synthetic data counts and separate Storage content recovery');
